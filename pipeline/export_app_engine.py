#!/usr/bin/env python3
"""Export the parameters of the rotation engine for the web app.

The app scores R0-R3 in the browser with `app/src/lib/calculator.ts`, a port of
`calculate_scores` in `pipeline/calculator.py`. Both must use the same numbers, so the app
does not copy them by hand: this script reads them from the same places as the pipeline
(`data/crops.csv`, `data/calibration.json` and the ROTATIONS and PROFILES of calculator.py)
and writes `app/src/data/engine.json`, which calculator.ts imports.

Run it after changing any of those files; `tests/test_export_app_engine.py` fails while
the JSON is out of date, and `node app/scripts/check-calculator.ts` checks that the app
still gives the pipeline's scores.

Usage:
    python3 -m pipeline.export_app_engine
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from pipeline.calculator import CALIBRATION_PATH, CROPS_PATH, PROFILES, ROTATIONS, load_calibration, load_crops

BASE_DIR = Path(__file__).resolve().parent.parent
OUT = BASE_DIR / "app" / "src" / "data" / "engine.json"

# Fields of load_crops() that calculate_scores uses, with the name they have in the app.
CROP_FIELDS = {
    "water_demand": "water",
    "cover_months": "cover",
    "nitrogen_fixer": "legume",
    "years_weight": "years",
    "market_ease": "market",
    "erosion_protection": "erosion",
    "organic_matter": "organic",
}


def _number(value):
    """1.0 -> 1 so the JSON reads like the CSV; booleans and fractions stay as they are."""
    if isinstance(value, float) and value.is_integer():
        return int(value)
    return value


def build(crops_path: Path = CROPS_PATH, calibration_path: Path = CALIBRATION_PATH) -> dict:
    crops = load_crops(crops_path)
    calibration = load_calibration(calibration_path)
    used = {c for info in ROTATIONS.values() for c in info["crops"]}
    missing = sorted(used - crops.keys())
    if missing:
        raise ValueError(f"Rotation crops missing from {crops_path.name}: {', '.join(missing)}")
    return {
        "_source": "Generated by pipeline/export_app_engine.py from data/crops.csv, data/calibration.json "
        "and pipeline/calculator.py. Do not edit by hand.",
        "crops": {
            cid: {app: _number(crops[cid][field]) for field, app in CROP_FIELDS.items()}
            for cid in sorted(used)
        },
        "rotations": {rid: info["crops"] for rid, info in ROTATIONS.items()},
        "profiles": PROFILES,
        "water_model": calibration.get("water_model", "deficit"),
        "water_reference_deficit_mm": _number(float(calibration["water_reference_deficit_mm"])),
    }


def render(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    args.out.write_text(render(build()), encoding="utf-8")
    print(f"OK {args.out.relative_to(BASE_DIR)}")


if __name__ == "__main__":
    main()
